import { fileURLToPath } from 'node:url';
import { TRPCError } from '@trpc/server';
import { and, count, eq, gte, lt } from 'drizzle-orm';
import type { Db } from '../../db/index.ts';
import { pomodoroSessions, pomodoroSettings } from '../../db/schema.ts';
import type { Run } from '../../core/exec.ts';
import { createLiveHub } from '../../core/live.ts';
import { copy } from './copy.ts';
import {
  createTimer,
  localMidnight,
  nextMidnight,
  timerState,
  transition,
  type Durations,
  type TimerAction,
} from './timer.ts';

export type Settings = Durations & { sound: boolean };

// Generated by `generate-chime.ts` next to it.
const chime = fileURLToPath(new URL('./chime.wav', import.meta.url));

export function createPomodoro(
  db: Db,
  run: Run,
  config: Durations,
  onError: (error: unknown) => void = () => {},
  onFocus: (tag: string) => void = () => {},
) {
  const now = Date.now();
  const completed =
    db
      .select({ value: count() })
      .from(pomodoroSessions)
      .where(
        and(
          eq(pomodoroSessions.kind, 'focus'),
          eq(pomodoroSessions.completed, true),
          gte(pomodoroSessions.endedAt, new Date(localMidnight(now))),
          lt(pomodoroSessions.endedAt, new Date(nextMidnight(now))),
        ),
      )
      .get()?.value ?? 0;
  const total =
    db
      .select({ value: count() })
      .from(pomodoroSessions)
      .where(and(eq(pomodoroSessions.kind, 'focus'), eq(pomodoroSessions.completed, true)))
      .get()?.value ?? 0;
  const saved = db.select().from(pomodoroSettings).get();
  let settings: Settings = saved
    ? {
        focusMinutes: saved.focusMinutes,
        shortBreakMinutes: saved.shortBreakMinutes,
        longBreakMinutes: saved.longBreakMinutes,
        longBreakEvery: saved.longBreakEvery,
        sound: saved.sound,
      }
    : { ...config, sound: true };
  let timer = createTimer(now, completed, total);
  let tag: string | undefined;
  // When the last phase ended by itself: the deck plays the chime when this changes.
  let lastCompletedAt: number | null = null;
  let deadline: NodeJS.Timeout | undefined;
  let closed = false;
  const hub = createLiveHub(() => Promise.resolve(state()), null);

  function schedule() {
    clearTimeout(deadline);
    if (closed) return;
    const at = Date.now();
    const end = Math.min(timer.endsAt ?? Infinity, nextMidnight(at));
    deadline = setTimeout(
      () => {
        try {
          settle();
          void hub.notify();
          schedule();
        } catch (error) {
          onError(error);
        }
      },
      Math.max(1, end - at),
    );
    deadline.unref();
  }

  function apply(action: TimerAction) {
    const result = transition(timer, action, settings, Date.now());
    if (!result) throw new TRPCError({ code: 'PRECONDITION_FAILED', message: 'Invalid Pomodoro transition' });
    if (result.ended) {
      db.insert(pomodoroSessions)
        .values({
          kind: result.ended.kind,
          startedAt: new Date(result.ended.startedAt),
          endedAt: new Date(result.ended.endedAt),
          completed: result.ended.completed,
          tag: result.ended.kind === 'focus' ? tag : undefined,
          durationMs: result.ended.completed ? timer.durationMs : undefined,
        })
        .run();
    }
    if (result.ended?.kind === 'focus') {
      if (result.ended.completed && tag) onFocus(tag);
      tag = undefined;
    }
    timer = result.timer;
    schedule();
    if (result.ended?.completed) {
      lastCompletedAt = result.ended.endedAt;
      const { title, body } = result.ended.kind === 'focus' ? copy.focusDone : copy.breakDone;
      void run('notify-send', ['--app-name', 'Hub', title, body]);
      if (settings.sound) void run('pw-play', [chime]);
    }
    void hub.notify();
  }

  function settle() {
    if (timer.endsAt !== null && timer.endsAt <= Date.now()) apply('complete');
  }

  function state() {
    settle();
    return { ...timerState(timer, Date.now()), tag: tag ?? null, settings, lastCompletedAt };
  }

  function today() {
    const now = Date.now();
    return db
      .select({ startedAt: pomodoroSessions.startedAt, endedAt: pomodoroSessions.endedAt, tag: pomodoroSessions.tag })
      .from(pomodoroSessions)
      .where(
        and(
          eq(pomodoroSessions.kind, 'focus'),
          eq(pomodoroSessions.completed, true),
          gte(pomodoroSessions.endedAt, new Date(localMidnight(now))),
          lt(pomodoroSessions.endedAt, new Date(nextMidnight(now))),
        ),
      )
      .orderBy(pomodoroSessions.startedAt)
      .all()
      .flatMap(({ startedAt, endedAt, tag }) =>
        endedAt === null ? [] : [{ startedAt: startedAt.getTime(), endedAt: endedAt.getTime(), tag }],
      );
  }

  function act(action: Exclude<TimerAction, 'complete'>, nextTag?: string) {
    settle();
    const previous = tag;
    if (action === 'start') tag = nextTag;
    try {
      apply(action);
    } catch (error) {
      tag = previous;
      throw error;
    }
  }

  /** Applies from the next phase: the running one keeps the duration it started with. */
  function configure(next: Settings) {
    const row = { id: 1, ...next, updatedAt: new Date() };
    db.insert(pomodoroSettings).values(row).onConflictDoUpdate({ target: pomodoroSettings.id, set: row }).run();
    settings = next;
    void hub.notify();
  }

  function close() {
    closed = true;
    clearTimeout(deadline);
  }

  /** The hub replays its last state to a late subscriber: `serverNow` is stamped when each value leaves, not when it was read. */
  async function* subscribe(signal?: AbortSignal) {
    for await (const value of hub.subscribe(signal)) yield { ...value, serverNow: Date.now() };
  }

  schedule();
  return { state, today, act, configure, subscribe, close };
}

export type PomodoroLive = ReturnType<typeof createPomodoro>;
